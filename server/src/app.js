import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import caseRoutes from './routes/caseRoutes.js';
import { ensureSession } from './middleware/accessControl.js';
import { errorHandler } from './middleware/errorHandler.js';
const app=express();
app.disable('x-powered-by');
app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173',credentials:true}));
app.use(express.json({limit:'32kb'})); app.use(cookieParser()); app.use(ensureSession);
app.get('/api/v1/health',(req,res)=>res.json({status:'ok'}));
app.use('/api/v1',rateLimit({windowMs:15*60*1000,limit:60,standardHeaders:'draft-7',legacyHeaders:false,message:{error:{code:'RATE_LIMITED',message:'Too many requests. Please try again shortly.'}}}));
app.use('/api/v1',caseRoutes);
app.use((req,res)=>res.status(404).json({error:{code:'NOT_FOUND',message:'The requested resource was not found.'}}));
app.use(errorHandler);
export default app;
